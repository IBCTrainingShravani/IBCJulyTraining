package sample;

public class SimpleLiterals {
public static void main(String[] args) {
	
	//1.whole numbers
	
	int age =25;
	long stars =9999999999L;
	
	//2. Decimal
	double price=19.99;
	float tax=0.05F;
	
	//3.others
	
	boolean isOpen = true;
	char grade ='A';
	
	System.out.println(age+","+stars+","+price+","+tax+","+isOpen+","+grade);
	
}
}
